#include <stdio.h>
#include <string.h>
#include "help_functions.h"
#include "ops.h"
#include "state.h"

#define HELP_WIDTH 78

/* Categories in order of first appearance in the table. */
static int categories(const char **out, int max) {
  int n = 0;
  for (int i = 0; i < n_ops; i++) {
    int seen = 0;
    for (int k = 0; k < n; k++)
      if (strcmp(out[k], ops[i].cat) == 0) { seen = 1; break; }
    if (!seen && n < max) out[n++] = ops[i].cat;
  }
  return n;
}

void splash_screen(void) {
  printf("\n  MM-14 %s -- Mico's simple RPN calculator\n", MM14_VERSION);
  printf("  Type 'help' for the command list, 'see <name>' for details, 'q' or Ctrl-D to quit.\n\n");
}

void help_screen(void) {
  const char *cats[32];
  int nc = categories(cats, 32);
  printf("All input is case sensitive. Separate tokens with spaces.\n");
  for (int c = 0; c < nc; c++) {
    char line[256];
    int len = snprintf(line, sizeof line, "  %-13s", cats[c]);
    for (int i = 0; i < n_ops; i++) {
      if (strcmp(ops[i].cat, cats[c]) != 0) continue;
      int nl = (int)strlen(ops[i].name);
      if (len + nl + 1 > HELP_WIDTH) {
        printf("%s\n", line);
        len = snprintf(line, sizeof line, "  %-13s", "");
      }
      len += snprintf(line + len, sizeof line - (size_t)len, " %s", ops[i].name);
    }
    printf("%s\n", line);
  }
  printf("'see <name>' describes a command or shows a user word's definition.\n");
}

void describe_op(int idx) {
  const Op *op = &ops[idx];
  if (op->args[0])
    printf("  %s   ( %s )   %s  [%s]\n", op->name, op->args, op->help, op->cat);
  else
    printf("  %s   %s  [%s]\n", op->name, op->help, op->cat);
}

static void md_escape(const char *s) {
  for (; *s; s++) {
    if (*s == '|') fputs("\\|", stdout);
    else putchar(*s);
  }
}

void print_commands_markdown(void) {
  const char *cats[32];
  int nc = categories(cats, 32);
  printf("# MM-14 command reference\n\n");
  printf("Generated by `mm_14 --commands` from the dispatch table; do not edit by hand.\n\n");
  printf("Stack pictures read left to right, deepest first: `y x -- result` means\n");
  printf("Y and X are consumed and `result` is left in X.\n");
  for (int c = 0; c < nc; c++) {
    printf("\n## %s\n\n| Command | Stack | Description |\n|---|---|---|\n", cats[c]);
    for (int i = 0; i < n_ops; i++) {
      if (strcmp(ops[i].cat, cats[c]) != 0) continue;
      printf("| `");
      md_escape(ops[i].name);
      printf("` | ");
      if (ops[i].args[0]) { printf("`"); md_escape(ops[i].args); printf("`"); }
      printf(" | ");
      md_escape(ops[i].help);
      printf(" |\n");
    }
  }
}
